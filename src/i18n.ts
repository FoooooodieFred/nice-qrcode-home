const dicts: Record<Locale, Dict> = { zh, en };
let current: Locale = 'zh';
/** Non-reactive read for core modules; the UI keeps it in sync via settings. */
export function setLocale(locale: Locale) {
  current = locale;
}
export function dictOf(locale: Locale): Dict {
  return dicts[locale] ?? zh;
}
export function dict(): Dict {
  return dictOf(current);
}
/** Replace {placeholders} in a dictionary string. */
export function fmt(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    key in vars ? String(vars[key]) : '{' + key + '}',
  );
}
